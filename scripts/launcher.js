function log(message) {
  const line = `[${new Date().toISOString()}] ${message}\n`;
  fs.appendFileSync(LAUNCHER_LOG, line, 'utf8');
  console.log(line.trim());
}

function parseEnv(content) {
  const result = {};
  for (const line of String(content || '').split(/\r?\n/)) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    const index = line.indexOf('=');
    if (index === -1) continue;
    result[line.slice(0, index).trim()] = line.slice(index + 1).trim();
  }
  return result;
}

function readEnv() {
  const source = fs.existsSync(ENV_FILE) ? ENV_FILE : ENV_EXAMPLE_FILE;
  return parseEnv(fs.existsSync(source) ? fs.readFileSync(source, 'utf8') : '');
}

function serializeEnv(values) {
  const order = [
    'DISCORD_TOKEN',
    'CLIENT_ID',
    'GUILD_ID',
    'CATEGORIE_DEFIS_ID',
    'JARLBOT_MODE',
    'EVA_COMPETITIVE_API_BASE_URL',
    'EVA_GRAPHQL_URL',
    'EVA_LOCAL_LEAGUES_CIRCUIT_ID',
    'EVA_MAJOR_TOURNAMENT_IDS',
    'EVA_V2_CACHE_TTL_MS',
    'EVA_V2_MIN_INTERVAL_MS',
    'EVA_V2_HTTP_TIMEOUT_MS',
    'EVA_V2_TEAM_MEMBER_REFRESH_LIMIT',
    'EVA_V2_TEAM_MEMBER_FULL_REFRESH_LIMIT',
    'EVA_V2_MAJOR_PLAYER_REFRESH_LIMIT',
    'EVA_V2_MAJOR_PLAYER_FULL_REFRESH_LIMIT',
    'EVA_V2_COMMAND_PLAYER_HYDRATE_LIMIT',
  ];
  const lines = [
    '# JarlBot local configuration',
    '# Generated by the local launcher. Keep DISCORD_TOKEN secret.',
  ];
  for (const key of order) {
    if (values[key] != null && values[key] !== '') lines.push(`${key}=${values[key]}`);
  }
  for (const [key, value] of Object.entries(values)) {
    if (!order.includes(key) && value != null && value !== '') lines.push(`${key}=${value}`);
  }
  return `${lines.join('\n')}\n`;
}

function writeEnv(updates) {
  const current = readEnv();
  const next = { ...current };
  for (const [key, value] of Object.entries(updates)) {
    if (value !== undefined && value !== null) next[key] = String(value).trim();
  }
  fs.writeFileSync(ENV_FILE, serializeEnv(next), 'utf8');
  Object.assign(process.env, next);
  log('Configuration .env mise a jour via le launcher.');
  return next;
}

function json(res, payload, statusCode = 200) {
  const body = JSON.stringify(payload);
  res.writeHead(statusCode, {
    'Content-Type': 'application/json; charset=utf-8',
    'Content-Length': Buffer.byteLength(body),
  });
  res.end(body);
}

function readBody(req) {
  return new Promise((resolve, reject) => {
    let data = '';
    req.on('data', chunk => {
      data += chunk;
      if (data.length > 1_000_000) {
        req.destroy();
        reject(new Error('Payload trop volumineux.'));
      }
    });
    req.on('end', () => {
      try {
        resolve(data ? JSON.parse(data) : {});
      } catch (err) {
        reject(err);
      }
    });
  });
}

function mask(value) {
  if (!value) return '';
  return `${String(value).slice(0, 4)}...${String(value).slice(-4)}`;
}

