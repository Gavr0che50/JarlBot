function log(message) {
  const line = `[${new Date().toISOString()}] ${message}\n`;
  fs.appendFileSync(LAUNCHER_LOG, line, 'utf8');
  console.log(line.trim());
}

function parseEnv(content) {
  const result = {};
  for (const line of String(content || '').split(/\r?\n/)) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    const index = line.indexOf('=');
    if (index === -1) continue;
    result[line.slice(0, index).trim()] = line.slice(index + 1).trim();
  }
  return result;
}

function readEnv() {
  const source = fs.existsSync(ENV_FILE) ? ENV_FILE : ENV_EXAMPLE_FILE;
  return parseEnv(fs.existsSync(source) ? fs.readFileSync(source, 'utf8') : '');
}

function serializeEnv(values) {
  const order = [
    'DISCORD_TOKEN',
    'CLIENT_ID',
    'GUILD_ID',
    'CATEGORIE_DEFIS_ID',
    'EVA_ACCESS_TOKEN',
    'EVA_COMPETITIVE_API_BASE_URL',
    'EVA_GRAPHQL_URL',
    'EVA_LOCAL_LEAGUES_CIRCUIT_ID',
    'EVA_MAJOR_TOURNAMENT_IDS',
    'EVA_V2_CACHE_TTL_MS',
    'EVA_V2_MIN_INTERVAL_MS',
    'EVA_V2_HTTP_TIMEOUT_MS',
    'EVA_V2_TEAM_MEMBER_REFRESH_LIMIT',
    'EVA_V2_TEAM_MEMBER_FULL_REFRESH_LIMIT',
    'EVA_V2_MAJOR_PLAYER_REFRESH_LIMIT',
    'EVA_V2_MAJOR_PLAYER_FULL_REFRESH_LIMIT',
    'EVA_V2_COMMAND_PLAYER_HYDRATE_LIMIT',
  ];
  const lines = [
    '# JarlBot local configuration',
    '# Generated by the local launcher. Keep DISCORD_TOKEN secret.',
  ];
  for (const key of order) {
    if (values[key] != null && values[key] !== '') lines.push(`${key}=${values[key]}`);
  }
  for (const [key, value] of Object.entries(values)) {
    if (!order.includes(key) && value != null && value !== '') lines.push(`${key}=${value}`);
  }
  return `${lines.join('\n')}\n`;
}

function writeEnv(updates) {
  const current = readEnv();
  const next = { ...current };
  for (const [key, value] of Object.entries(updates)) {
    if (value !== undefined && value !== null) next[key] = String(value).trim();
  }
  fs.writeFileSync(ENV_FILE, serializeEnv(next), 'utf8');
  Object.assign(process.env, next);
  log('Configuration .env mise a jour via le launcher.');
  return next;
}

function json(res, payload, statusCode = 200) {
  const body = JSON.stringify(payload);
  res.writeHead(statusCode, {
    'Content-Type': 'application/json; charset=utf-8',
    'Content-Length': Buffer.byteLength(body),
  });
  res.end(body);
}

function readBody(req) {
  return new Promise((resolve, reject) => {
    let data = '';
    req.on('data', chunk => {
      data += chunk;
      if (data.length > 1_000_000) {
        req.destroy();
        reject(new Error('Payload trop volumineux.'));
      }
    });
    req.on('end', () => {
      try {
        resolve(data ? JSON.parse(data) : {});
      } catch (err) {
        reject(err);
      }
    });
  });
}

function mask(value) {
  if (!value) return '';
  return `${String(value).slice(0, 4)}...${String(value).slice(-4)}`;
}

function buildInviteUrl(clientId) {
  if (!clientId) return '';
  const permissions = [
    1n << 4n,  // ManageChannels
    1n << 6n,  // AddReactions
    1n << 10n, // ViewChannel
    1n << 11n, // SendMessages
    1n << 16n, // ReadMessageHistory
    1n << 17n, // MentionEveryone
    1n << 28n, // ManageRoles
    1n << 33n, // ManageEvents
  ].reduce((sum, bit) => sum + bit, 0n);
  const params = new URLSearchParams({
    client_id: clientId,
    permissions: permissions.toString(),
    scope: 'bot applications.commands',
  });
  return `https://discord.com/oauth2/authorize?${params.toString()}`;
}

function getDbStatus() {
  try {
    delete require.cache[require.resolve('../utils/eva-v2')];
    const { getEvaV2Status } = require('../utils/eva-v2');
    return getEvaV2Status();
  } catch (err) {
    return { error: err.message };
  }
}

function tail(file, maxLines = 160) {
  if (!fs.existsSync(file)) return '';
  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/);
  return lines.slice(Math.max(0, lines.length - maxLines)).join('\n');
}

function startBot() {
  if (botProcess && !botProcess.killed) return { started: false, message: 'Bot deja lance par le launcher.' };
  const out = fs.openSync(BOT_OUT_LOG, 'a');
  const err = fs.openSync(BOT_ERR_LOG, 'a');
  botProcess = spawn(process.execPath, ['index.js'], {
    cwd: ROOT,
    detached: false,
    stdio: ['ignore', out, err],
    env: { ...process.env, ...readEnv() },
  });
  botProcess.on('exit', code => {
    log(`Bot arrete avec code ${code}.`);
    botProcess = null;
  });
  log(`Bot lance (pid ${botProcess.pid}).`);
  return { started: true, pid: botProcess.pid };
}

function stopBot() {
  if (!botProcess || botProcess.killed) return { stopped: false, message: 'Aucun bot lance par le launcher.' };
  const pid = botProcess.pid;
  botProcess.kill();
  log(`Arret demande du bot (pid ${pid}).`);
  return { stopped: true, pid };
}

function startRefresh(mode) {
  if (refreshProcess && !refreshProcess.killed) return { started: false, message: 'Refresh deja en cours.' };
  const args = ['scripts/eva-refresh.js'];
  if (mode === 'reset') args.push('--reset', '--full');
  if (mode === 'full') args.push('--full');
  const out = fs.openSync(REFRESH_LOG, 'a');
  refreshProcess = spawn(process.execPath, args, {
    cwd: ROOT,
    detached: false,
    stdio: ['ignore', out, out],
    env: { ...process.env, ...readEnv() },
  });
  refreshProcess.on('exit', code => {
    log(`Refresh EVA termine avec code ${code}.`);
    refreshProcess = null;
  });
  log(`Refresh EVA lance (${mode || 'normal'}, pid ${refreshProcess.pid}).`);
  return { started: true, pid: refreshProcess.pid };
}

function runExport() {
  return new Promise(resolve => {
    const child = spawn(process.execPath, ['scripts/export-portable.js'], {
      cwd: ROOT,
      env: { ...process.env, ...readEnv() },
    });
    let output = '';
    child.stdout.on('data', chunk => { output += chunk.toString(); });
    child.stderr.on('data', chunk => { output += chunk.toString(); });
    child.on('exit', code => {
      log(`Export portable termine avec code ${code}.`);
      resolve({ code, output });
    });
  });
}

function openBrowser(url) {
  const command = process.platform === 'win32'
    ? ['cmd', ['/c', 'start', '', url]]
    : process.platform === 'darwin'
      ? ['open', [url]]
      : ['xdg-open', [url]];
  spawn(command[0], command[1], { detached: true, stdio: 'ignore' }).unref();
}

