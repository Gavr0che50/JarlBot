function tail(file, maxLines = 160) {
  if (!fs.existsSync(file)) return '';
  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/);
  return lines.slice(Math.max(0, lines.length - maxLines)).join('\n');
}

function deploySlashCommands() {
  if (deployProcess && !deployProcess.killed) return;
  const deployOut = fs.openSync(LAUNCHER_LOG, 'a');
  deployProcess = spawn(process.execPath, ['deploy-commands.js'], {
    cwd: ROOT,
    stdio: ['ignore', deployOut, deployOut],
    env: { ...process.env, ...readEnv() },
  });
  deployProcess.on('exit', code => {
    log(`Deploy slash commands termine avec code ${code}.`);
    deployProcess = null;
  });
  log(`Deploy slash commands lance (pid ${deployProcess.pid}).`);
}

function spawnBotProcess() {
  const out = fs.openSync(BOT_OUT_LOG, 'a');
  const err = fs.openSync(BOT_ERR_LOG, 'a');
  const child = spawn(process.execPath, ['index.js'], {
    cwd: ROOT,
    detached: false,
    stdio: ['ignore', out, err],
    env: { ...process.env, ...readEnv() },
  });
  botProcess = child;
  child.on('exit', code => {
    log(`Bot arrete avec code ${code}.`);
    if (botProcess === child) botProcess = null;
  });
  log(`Bot lance (pid ${botProcess.pid}).`);
  return child;
}

function startBot() {
  let restarted = false;
  if (botProcess && !botProcess.killed) {
    const oldPid = botProcess.pid;
    botProcess.kill();
    restarted = true;
    log(`Redemarrage du bot demande pour appliquer la configuration (ancien pid ${oldPid}).`);
  }
  const child = spawnBotProcess();
  deploySlashCommands();
  return {
    started: true,
    restarted,
    pid: child.pid,
    message: restarted ? 'Bot redemarre + slash commands enregistrees.' : 'Bot lance + slash commands enregistrees.',
  };
}

function stopBot() {
  if (!botProcess || botProcess.killed) return { stopped: false, message: 'Aucun bot lance par le launcher.' };
  const pid = botProcess.pid;
  botProcess.kill();
  log(`Arret demande du bot (pid ${pid}).`);
  return { stopped: true, pid };
}

function startRefresh(mode) {
  if (refreshProcess && !refreshProcess.killed) return { started: false, message: 'Refresh deja en cours.' };
  const args = ['scripts/eva-refresh.js'];
  if (mode === 'reset') args.push('--reset', '--full');
  if (mode === 'full') args.push('--full');
  const out = fs.openSync(REFRESH_LOG, 'a');
  refreshProcess = spawn(process.execPath, args, {
    cwd: ROOT,
    detached: false,
    stdio: ['ignore', out, out],
    env: { ...process.env, ...readEnv() },
  });
  refreshProcess.on('exit', code => {
    log(`Refresh EVA termine avec code ${code}.`);
    refreshProcess = null;
  });
  log(`Refresh EVA lance (${mode || 'normal'}, pid ${refreshProcess.pid}).`);
  return { started: true, pid: refreshProcess.pid };
}

function runExport() {
  return new Promise(resolve => {
    const child = spawn(process.execPath, ['scripts/export-portable.js'], {
      cwd: ROOT,
      env: { ...process.env, ...readEnv() },
    });
    let output = '';
    child.stdout.on('data', chunk => { output += chunk.toString(); });
    child.stderr.on('data', chunk => { output += chunk.toString(); });
    child.on('exit', code => {
      log(`Export portable termine avec code ${code}.`);
      resolve({ code, output });
    });
  });
}

function openBrowser(url) {
  const command = process.platform === 'win32'
    ? ['cmd', ['/c', 'start', '', url]]
    : process.platform === 'darwin'
      ? ['open', [url]]
      : ['xdg-open', [url]];
  spawn(command[0], command[1], { detached: true, stdio: 'ignore' }).unref();
}

