async function handle(req, res) {
  try {
    const url = new URL(req.url, `http://localhost:${PORT}`);
    if (req.method === 'GET' && url.pathname === '/') {
      res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' });
      res.end(html);
      return;
    }
    if (req.method === 'GET' && url.pathname === '/api/status') {
      const env = readEnv();
      json(res, {
        env: {
          CLIENT_ID: env.CLIENT_ID || '',
          GUILD_ID: env.GUILD_ID || '',
          CATEGORIE_DEFIS_ID: env.CATEGORIE_DEFIS_ID || '',
          DISCORD_TOKEN: mask(env.DISCORD_TOKEN),
          EVA_ACCESS_TOKEN: mask(env.EVA_ACCESS_TOKEN),
        },
        inviteUrl: buildInviteUrl(env.CLIENT_ID),
        botRunning: Boolean(botProcess && !botProcess.killed),
        refreshRunning: Boolean(refreshProcess && !refreshProcess.killed),
        db: getDbStatus(),
      });
      return;
    }
    if (req.method === 'POST' && url.pathname === '/api/config') {
      const body = await readBody(req);
      writeEnv(body);
      json(res, { ok: true });
      return;
    }
    if (req.method === 'POST' && url.pathname === '/api/bot/start') {
      json(res, startBot());
      return;
    }
    if (req.method === 'POST' && url.pathname === '/api/bot/stop') {
      json(res, stopBot());
      return;
    }
    if (req.method === 'POST' && url.pathname === '/api/refresh') {
      const body = await readBody(req);
      const result = startRefresh(body.mode || 'normal');
      json(res, { ...result, message: result.started ? `Refresh ${body.mode || 'normal'} lance.` : result.message });
      return;
    }
    if (req.method === 'POST' && url.pathname === '/api/deploy') {
      if (deployProcess && !deployProcess.killed) {
        json(res, { ok: false, message: 'Enregistrement deja en cours.' });
        return;
      }
      const out = fs.openSync(LAUNCHER_LOG, 'a');
      deployProcess = spawn(process.execPath, ['deploy-commands.js'], {
        cwd: ROOT,
        stdio: ['ignore', out, out],
        env: { ...process.env, ...readEnv() },
      });
      deployProcess.on('exit', code => {
        log(`Deploy slash commands termine avec code ${code}.`);
        deployProcess = null;
      });
      log(`Deploy slash commands lance (pid ${deployProcess.pid}).`);
      json(res, { ok: true, message: 'Enregistrement des commandes lance.' });
      return;
    }
    if (req.method === 'POST' && url.pathname === '/api/export') {
      const result = await runExport();
      json(res, result, result.code === 0 ? 200 : 500);
      return;
    }
    if (req.method === 'GET' && url.pathname === '/api/logs') {
      const kind = url.searchParams.get('kind') || 'bot';
      const file = kind === 'error' ? BOT_ERR_LOG : kind === 'refresh' ? REFRESH_LOG : kind === 'launcher' ? LAUNCHER_LOG : BOT_OUT_LOG;
      json(res, { logs: tail(file) });
      return;
    }
    json(res, { error: 'Route introuvable.' }, 404);
  } catch (err) {
    log(`Erreur launcher: ${err.stack || err.message}`);
    json(res, { error: err.message }, 500);
  }
}

const server = http.createServer((req, res) => {
  handle(req, res);
});

server.listen(PORT, () => {
  const url = `http://localhost:${PORT}`;
  log(`Launcher disponible sur ${url}`);
  if (process.env.JARLBOT_LAUNCHER_NO_OPEN !== '1') openBrowser(url);
});
